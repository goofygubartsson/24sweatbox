export type SweatboxConfig = z.infer<typeof ConfigSchema>;
export type SweatboxConfigInput = z.input<typeof ConfigSchema>;

/** Validate a config object. Throws an Error listing every bad key. */
export function validateConfig(raw: unknown): SweatboxConfig {
  const res = ConfigSchema.safeParse(raw);
  if (res.success) {
    const c = res.data;
    if (c.session.minSpeed > c.session.maxSpeed) throw new Error("sweatbox.config.ts: session.minSpeed > session.maxSpeed");
    return c;
  }
  const lines = res.error.issues.map((i) => `  - ${i.path.join(".") || "(root)"}: ${i.message}`);
  throw new Error(`sweatbox.config.ts is invalid:\n${lines.join("\n")}`);
}
